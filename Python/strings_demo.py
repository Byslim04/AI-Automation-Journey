# Пример работы со строками и числами
text = "python automation"
numer = 42

# Метод строк
print(text.upper())          # B верхний регистр: PYTHON AUTOMATION
print(text.title())          # C заглавной буквы: Python Automation
print(f"Результат вычислений: {number * 2}")  # Работа с числами: 84



